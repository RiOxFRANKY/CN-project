# ------------------------------------------------------------------ timeline
def describe(m):
    if m.startswith("Data(["):
        nums = [int(x) for x in m[6:-2].split(", ")]
        s = bytes(nums).decode(errors="replace").replace("\n", "\\n")
        return "Data(``" + tex(s if len(s) < 34 else s[:31] + "...") + "'')"
    if m.startswith("SessionKey"):
        return "SessionKey(44-byte RSA ciphertext)"
    if m.startswith("Auth"):
        return "Auth(student, $n_c$, $e$, $\\sigma$)"
    if m.startswith("HostKey"):
        return "HostKey($n_h$, $e$)"
    return tex(m.replace('"', "``", 1).replace('"', "''", 1))


