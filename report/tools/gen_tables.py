def tex(s):
    out = []
    for ch in s:
        out.append({
            "\\": r"\textbackslash{}", "_": r"\_", "&": r"\&", "%": r"\%", "$": r"\$",
            "#": r"\#", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        }.get(ch, ch))
    return "".join(out)


def write(name, text):
    with open(os.path.join(GEN, name), "w") as f:
        f.write("% generated by tools/gen_tables.py from data/ -- do not edit\n" + text)


def b(hexstr):
    return hexstr.split() if hexstr else []


def grouped(n, k=3):
    """Digits of n in groups of k for readability."""
    s = str(n)
    parts = []
    while s:
        parts.insert(0, s[-k:])
        s = s[:-k]
    return r"\,".join(parts)


DIR = {"c2s": r"C$\to$S", "s2c": r"S$\to$C"}


def show_char(h):
    v = int(h, 16)
    if v == 10:
        return r"\textbackslash n"
    if 32 < v < 127:
        return tex(chr(v))
    if v == 32:
        return r"\textvisiblespace"
    return r"$\cdot$"


