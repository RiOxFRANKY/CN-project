def fields(msg, plain):
    """Name each plaintext byte by the field it belongs to."""
    n = len(plain)
    tag = ["tag"]
    if msg.startswith("Auth"):
        ul = int("".join(plain[1:5]), 16)
        return tag + ["len"] * 4 + ["user"] * ul + ["$n_c$"] * 8 + ["$e$"] * 8 + ["$\\sigma$"] * 8
    if msg.startswith(("Data", "Success", "Failure")):
        return tag + ["len"] * 4 + ["text"] * (n - 5)
    if msg.startswith("Exit"):
        return tag + ["code"] * 8
    return tag * n


def xor_table(f, per_row=12):
    plain, ks = b(f["plain"]), b(f["keystream"])
    wire = b(f["wire"])
    head, body = wire[:4], wire[4:]
    names = fields(f["msg"], plain)
    stream = 'client$\\to$server' if f['dir'] == 'c2s' else 'server$\\to$client'
    out = ["{\\footnotesize length prefix in clear: \\texttt{" + ' '.join(head) + "} $= " + str(len(body)) + "$; "
           "keystream bytes " + str(f['offset']) + "--" + str(f['offset'] + len(body) - 1) + " of the " + stream + " stream\\par\\smallskip}",
           "{\\setlength{\\tabcolsep}{3pt}\\footnotesize",
           "\\begin{tabular}{@{}l" + "c" * per_row + "@{}}", "\\toprule"]
    for start in range(0, len(body), per_row):
        sl = slice(start, start + per_row)
        pad = per_row - len(plain[sl])
        def row(label, cells):
            return label + " & " + " & ".join(cells) + " &" * pad + " \\\\"
        if start:
            out.append("\\midrule")
        # merge equal field names into multicolumns
        cells, prev, span = [], None, 0
        for nm in names[sl] + [None]:
            if nm == prev:
                span += 1
                continue
            if prev is not None:
                cells.append(f"\\multicolumn{{{span}}}{{c}}{{\\scriptsize\\itshape {prev}}}" if span > 1 else f"{{\\scriptsize\\itshape {prev}}}")
            prev, span = nm, 1
        out.append("field & " + " & ".join(cells) + " &" * pad + " \\\\")
        out.append(row("plaintext", [f"\\texttt{{{x}}}" for x in plain[sl]]))
        out.append(row("as text", [f"\\texttt{{{show_char(x)}}}" for x in plain[sl]]))
        out.append(row("$\\oplus$ keystream", [f"\\texttt{{{x}}}" for x in ks[sl]]))
        out.append(row("= on the wire", [f"\\texttt{{\\textbf{{{x}}}}}" for x in body[sl]]))
    out += ["\\bottomrule", "\\end{tabular}}", ""]
    return "\n".join(out)


def find(prefix, dirn, nth=0):
    hits = [f for f in frames if f["msg"].startswith(prefix) and f["dir"] == dirn]
    return hits[nth]


